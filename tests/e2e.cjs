// Run against tests/.runtime only. All credentials here are isolated test fixtures.
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const { mkdirSync } = require('node:fs');
const { resolve } = require('node:path');
const { chromium, request } = require(process.env.FR_PLAYWRIGHT_MODULE || '../app/node_modules/playwright');
const origin = 'http://127.0.0.1:8095';
const api = '/wp-json/fitet-ricevute/v1/';
const credentials = { username: 'fr-tester', password: 'FR-test-only-2026!', remember: false };
const headers = { Origin: origin, 'X-FR-Request': '1' };
let checks = 0;
function ok(value, message) { assert.ok(value, message); checks++; console.log('PASS', message); }
function control(action) {
  const result = spawnSync('php', ['tests/control.php', action], { cwd: resolve(__dirname, '..'), encoding: 'utf8' });
  assert.equal(result.status, 0, result.stdout + result.stderr);
}

(async () => {
  control('enable'); control('portal-on'); control('clear-rate-limit');
  const client = await request.newContext({ baseURL: origin, extraHTTPHeaders: headers });
  const bare = await request.newContext({ baseURL: origin });
  let res = await client.get(api + 'config');
  const config = await res.json();
  ok(res.status() === 200 && !('session_hours' in config) && !('society_code' in config), 'public config exposes only public fields');
  ok(res.headers()['cache-control'].includes('no-store'), 'API responses are not cached');
  ok((await client.get('/?rest_route=/fitet-ricevute/v1/config')).status() === 200, 'API works with plain permalink form');
  ok((await client.get(api + 'auth/me')).status() === 401, 'anonymous access is rejected');
  ok((await bare.post(api + 'auth/login', { data: credentials })).status() === 403, 'login without origin/request header is rejected');
  ok((await client.post(api + 'auth/login', { data: {}, })).status() === 400, 'malformed login is rejected');
  ok((await client.post(api + 'auth/login', { data: { ...credentials, password: 'wrong' } })).status() === 401, 'incorrect password is rejected');
  res = await client.post(api + 'auth/login', { data: credentials });
  const session = await res.json();
  ok(res.status() === 200 && session.user.username === credentials.username, 'valid login succeeds');
  ok(!JSON.stringify(session).includes('password') && !('token' in session), 'no password or session token in login JSON');
  const cookie = (await client.storageState()).cookies.find(c => c.name.startsWith('fitet_ricevute_'));
  ok(cookie && cookie.httpOnly && cookie.sameSite === 'Lax' && cookie.expires === -1, 'session cookie is HttpOnly, SameSite Lax and nonpersistent');
  res = await client.get(api + 'auth/me');
  const restored = await res.json();
  ok(res.status() === 200 && restored.csrf_token === session.csrf_token, 'session and CSRF restore from cookie (status=' + res.status() + ', code=' + restored.code + ')');
  ok((await client.get(api + 'auth/me', { headers: { Origin: 'https://evil.example' } })).status() === 403, 'authenticated cross-origin read is rejected');
  res = await client.post(api + 'auth/logout', { data: {} });
  ok(res.status() === 403, 'logout without CSRF is rejected (status=' + res.status() + ')');
  ok((await client.post(api + 'auth/logout', { headers: { 'X-FR-CSRF': session.csrf_token, Origin: 'https://evil.example' }, data: {} })).status() === 403, 'cross-origin logout is rejected');
  ok((await client.post(api + 'auth/logout', { headers: { 'X-FR-CSRF': session.csrf_token }, data: {} })).status() === 200, 'valid logout succeeds');
  const replay = await request.newContext({ baseURL: origin, extraHTTPHeaders: { ...headers, Cookie: `${cookie.name}=${cookie.value}` } });
  ok((await replay.get(api + 'auth/me')).status() === 401, 'logged-out token cannot be replayed');
  res = await client.post(api + 'auth/login', { data: { ...credentials, remember: true } });
  ok(res.status() === 200 && (await client.storageState()).cookies.some(c => c.expires > Date.now() / 1000 + 86400), 'remember-me creates a persistent cookie');
  control('expire');
  ok((await client.get(api + 'auth/me')).status() === 401, 'expired session is rejected');
  await client.post(api + 'auth/login', { data: credentials });
  control('disable');
  ok((await client.get(api + 'auth/me')).status() === 401, 'disabled user loses active access');
  ok((await client.post(api + 'auth/login', { data: credentials })).status() === 401, 'disabled user cannot log in');
  control('enable');
  ok((await client.get(api + 'auth/me')).status() === 401, 'reenabling an account does not revive revoked sessions');
  await client.post(api + 'auth/login', { data: credentials });
  control('reset-password');
  ok((await client.get(api + 'auth/me')).status() === 401, 'password reset revokes active sessions');
  res = await client.post(api + 'auth/login', { data: credentials });
  const beforeDisabled = await res.json();
  control('portal-off');
  ok((await client.get(api + 'auth/me')).status() === 503, 'portal switch blocks authenticated operations');
  ok((await client.post(api + 'auth/logout', { headers: { 'X-FR-CSRF': beforeDisabled.csrf_token }, data: {} })).status() === 200, 'logout remains available when portal is disabled');
  control('portal-on'); control('clear-rate-limit');
  for (let i = 0; i < 10; i++) await client.post(api + 'auth/login', { data: { ...credentials, password: 'wrong' } });
  res = await client.post(api + 'auth/login', { data: credentials });
  ok(res.status() === 429 && res.headers()['retry-after'] === '900', 'repeated failures trigger rate limit and Retry-After');
  control('clear-rate-limit');
  await client.dispose(); await bare.dispose(); await replay.dispose();

  const browser = await chromium.launch({ headless: true, ...(process.env.FR_BROWSER_PATH ? { executablePath: process.env.FR_BROWSER_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  mkdirSync(resolve(__dirname, 'screenshots'), { recursive: true });
  await page.goto(origin + '/fitet-ricevute/');
  await page.getByRole('heading', { name: 'Accedi al portale' }).waitFor();
  await page.getByLabel('Username', { exact: true }).waitFor();
  await page.screenshot({ path: resolve(__dirname, 'screenshots/login-desktop.png'), fullPage: true });
  ok(page.url().includes('/login'), 'guard redirects anonymous browser to login');
  await page.getByLabel('Username', { exact: true }).fill(credentials.username);
  await page.getByLabel('Password', { exact: true }).fill('wrong');
  await page.getByRole('button', { name: 'Accedi', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Username o password non validi.' }).waitFor();
  ok(await page.getByLabel('Password', { exact: true }).inputValue() === '', 'failed UI login clears password and displays error');
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Mostra password' }).click();
  await page.getByRole('button', { name: 'Nascondi password' }).waitFor();
  ok(await page.getByLabel('Password', { exact: true }).getAttribute('type') === 'text', 'password visibility control works');
  await page.getByRole('button', { name: 'Accedi', exact: true }).click();
    await page.getByRole('heading', { name: 'Prezzi tornei', exact: true }).waitFor();
  ok(new URL(page.url()).pathname === '/fitet-ricevute/', 'Angular navigation preserves the WordPress portal URL');
    ok(await page.locator('#prices-grid').count() === 1 && await page.locator('#entries-grid').count() === 0, 'prices occupy a separate AG Grid page');
    ok(await page.getByRole('link', { name: 'Iscrizioni', exact: true }).count() === 1, 'navigation exposes the separate entries page');
    ok(await page.evaluate(() => Object.keys(localStorage).every(key => key.startsWith('fr:tables:v1:') && !/password|csrf_token|session_token/.test(localStorage.getItem(key)))), 'localStorage contains table preferences only, without authentication credentials');
  await page.reload();
    await page.getByRole('heading', { name: 'Prezzi tornei', exact: true }).waitFor();
  ok(true, 'refresh restores authenticated session');
  await page.screenshot({ path: resolve(__dirname, 'screenshots/dashboard-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Esci', exact: true }).click();
  await page.getByRole('heading', { name: 'Accedi al portale' }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Accedi al portale' }).waitFor();
  await page.getByLabel('Username', { exact: true }).waitFor();
  ok(true, 'browser logout persists after refresh');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(__dirname, 'screenshots/login-mobile.png'), fullPage: true });
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile login has no horizontal overflow');
  ok(errors.length === 0, 'Angular runs without uncaught browser errors: ' + errors.join('; '));

  // Real WordPress administration: capability/nonce-protected configuration and account forms.
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(origin + '/wp-login.php');
  await page.locator('#user_login').fill('wp-test-admin');
  await page.locator('#user_pass').fill('WP-test-only-2026!');
  await page.locator('#wp-submit').click();
  await page.waitForURL('**/wp-admin/**');
  await page.goto(origin + '/wp-admin/admin.php?page=fitet-ricevute');
  await page.locator('#fr-society_name').fill('Società di test');
  await page.getByRole('button', { name: 'Salva impostazioni' }).click();
  ok(await page.locator('#fr-society_name').inputValue() === 'Società di test', 'wp-admin settings save correctly');
  await page.goto(origin + '/wp-admin/admin.php?page=fitet-ricevute-users');
  await page.getByRole('heading', { name: 'Crea utente', exact: true }).waitFor();
  const username = 'new-test-' + Date.now();
  await page.locator('#fr-username').fill(username);
  await page.locator('#fr-name').fill('Nuovo operatore');
  await page.locator('#fr-password').fill('New-test-only-2026!');
  await page.getByRole('button', { name: 'Crea utente', exact: true }).click();
  await page.getByText('Utente salvato.', { exact: false }).waitFor();
  ok(await page.getByRole('cell', { name: username, exact: true }).count() === 1, 'wp-admin can create a portal account');
  const newClient = await request.newContext({ baseURL: origin, extraHTTPHeaders: headers });
  ok((await newClient.post(api + 'auth/login', { data: { username, password: 'New-test-only-2026!' } })).status() === 200, 'account created in wp-admin can authenticate via API');
  await newClient.dispose();
  await context.close(); await browser.close();
  console.log(`\n${checks} checks passed.`);
  await require('./data-ui.cjs')();
})().catch(error => { console.error(error); process.exit(1); });
