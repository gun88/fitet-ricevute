const assert = require('node:assert/strict');
const { chromium, request } = require(process.env.FR_PLAYWRIGHT_MODULE || '../app/node_modules/playwright');
const { resolve } = require('node:path');
const origin = 'http://127.0.0.1:8095';
const configUrl = origin + '/wp-admin/admin.php?page=fitet-ricevute';
let checks = 0;
function ok(value, label) { assert.ok(value, label); checks++; console.log('PASS', label); }
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.FR_BROWSER_PATH ? { executablePath: process.env.FR_BROWSER_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1280, height: 1200 } });
  const page = await context.newPage();
  await page.goto(origin + '/wp-login.php');
  await page.locator('#user_login').fill('wp-test-admin');
  await page.locator('#user_pass').fill('WP-test-only-2026!');
  await page.locator('#wp-submit').click();
  await page.waitForURL('**/wp-admin/**');
  await page.goto(configUrl);
  const password = '  UI-FITeT-test\\"<>&-2026!  ';
  await page.getByLabel('Username extranet FITeT', { exact: true }).fill('Societa.UI-test');
  await page.getByLabel('Password extranet FITeT', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Salva credenziali FITeT' }).click();
  await page.getByText('Credenziali extranet FITeT salvate.', { exact: true }).waitFor();
  ok(await page.locator('#fr-extranet-username').inputValue() === 'Societa.UI-test', 'extranet username is persisted from wp-admin');
  ok(await page.locator('#fr-extranet-password').inputValue() === '', 'saved password is never prefilled');
  ok(await page.getByText('Password già salvata.', { exact: false }).count() === 1, 'saved-password status is visible');
  ok(!(await page.content()).includes(password), 'password is absent from the HTML response');
  await page.getByRole('button', { name: 'Salva credenziali FITeT' }).click();
  await page.getByText('Credenziali extranet FITeT salvate.', { exact: true }).waitFor();
  ok(await page.getByText('Password già salvata.', { exact: false }).count() === 1, 'saving blank password preserves it');
  await page.getByRole('button', { name: 'Salva impostazioni', exact: true }).click();
  ok(await page.getByText('Password già salvata.', { exact: false }).count() === 1, 'general settings do not overwrite extranet credentials');
  const publicClient = await request.newContext();
  let response = await publicClient.get(origin + '/wp-json/fitet-ricevute/v1/config');
  const body = await response.text();
  ok(response.status() === 200 && !body.includes('Societa.UI-test') && !body.includes('password'), 'public REST API does not expose extranet credentials');
  response = await context.request.post(origin + '/wp-admin/admin-post.php', { form: { action: 'fitet_ricevute_save_extranet', _wpnonce: 'invalid', 'extranet[username]': 'attacker' } });
  ok(response.status() === 403, 'invalid nonce cannot modify credentials');
  response = await publicClient.post(origin + '/wp-admin/admin-post.php', { form: { action: 'fitet_ricevute_save_extranet', 'extranet[username]': 'attacker' } });
  ok(response.status() >= 400, 'anonymous visitor cannot save credentials');
  await page.goto(configUrl);
  ok(await page.locator('#fr-extranet-username').inputValue() === 'Societa.UI-test', 'rejected requests leave stored credentials unchanged');
  await page.screenshot({ path: resolve(__dirname, 'screenshots/extranet-admin.png'), fullPage: true });
  await page.getByLabel('Rimuovi la password extranet FITeT salvata', { exact: true }).check();
  await page.getByRole('button', { name: 'Salva credenziali FITeT' }).click();
  await page.getByText('Nessuna password salvata.', { exact: true }).waitFor();
  ok(true, 'explicit removal works from wp-admin');
  await publicClient.dispose(); await context.close(); await browser.close();
  console.log(`${checks} extranet UI checks passed.`);
})().catch(error => { console.error(error); process.exit(1); });
