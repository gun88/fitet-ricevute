const assert = require('node:assert/strict');
const { resolve } = require('node:path');
const { mkdirSync, readFileSync, writeFileSync } = require('node:fs');
const { unzipSync } = require('../app/node_modules/fflate');
const { chromium, request } = require(process.env.FR_PLAYWRIGHT_MODULE || '../app/node_modules/playwright');
module.exports = async () => {
  const origin = 'http://127.0.0.1:8095'; const api = origin + '/wp-json/fitet-ricevute/v1/';
  const client = await request.newContext({ extraHTTPHeaders: { Origin: origin, 'X-FR-Request': '1' } });
  let checks = 0;
  function ok(value, message) { assert.ok(value, message); checks++; console.log('PASS', message); }
  let response = await client.get(api + 'gare'); ok(response.status() === 401, 'race data requires authentication');
  response = await client.post(api + 'auth/login', { data: { username: 'fr-tester', password: 'FR-test-only-2026!' } });
  const session = await response.json();
  const headers = { Origin: origin, 'X-FR-Request': '1', 'X-FR-CSRF': session.csrf_token };
  let races = await (await client.get(api + 'gare')).json();
  const id = races.items[0].id;
  let entries = await (await client.get(api + 'iscrizioni')).json();
  const ids = entries.items.map(row => Number(row.id));
  await client.patch(api + 'rimborsi/stato', { headers, data: { ids, reimbursed: false } });
  for (const race of races.items) await client.patch(api + 'prezzi/' + race.id, { headers, data: { manual_cents: null } });
  ok(races.total === 2 && entries.total === 6, 'API joins both source tables with prices');
  ok(races.items.every(row => row.committee_label === 'Lombardia'), 'API adds committee names from public FITeT menu');
  ok((await client.patch(api + 'prezzi/' + id, { data: { manual_cents: 1250 } })).status() === 403, 'price edit requires CSRF');
  ok((await client.patch(api + 'prezzi/' + id, { headers, data: { manual_cents: -1 } })).status() === 400, 'negative price rejected');
  ok((await client.patch(api + 'prezzi/' + id, { headers, data: {} })).status() === 422, 'omitted price cannot clear manual override');
  ok((await client.patch(api + 'prezzi/' + id, { headers, data: { manual_cents: null } })).status() === 200, 'explicit null resets automatic price');
  ok((await client.post(api + 'rimborsi/anteprima', { data: { ids: [ids[0]] } })).status() === 403, 'refund preview requires CSRF');
  ok((await client.patch(api + 'rimborsi/stato', { data: { ids: [ids[0]], reimbursed: true } })).status() === 403, 'refund mutation requires CSRF');
  ok((await client.post(api + 'rimborsi/anteprima', { headers, data: { ids: [99999999] } })).status() === 422, 'stale refund selection rejected');
  ok((await client.post(api + 'rimborsi/anteprima', { headers, data: { ids: [] } })).status() === 400, 'empty selection rejected');
  ok((await client.patch(api + 'rimborsi/stato', { headers, data: { ids: [ids[0]] } })).status() === 400, 'refund status must be explicit');

  const browser = await chromium.launch({ headless: true, ...(process.env.FR_BROWSER_PATH ? { executablePath: process.env.FR_BROWSER_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1100 }, acceptDownloads: true });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  mkdirSync(resolve(__dirname, 'screenshots'), { recursive: true });
  const out = resolve(__dirname, '.runtime/refund-output'); mkdirSync(out, { recursive: true });
  const row = grid => page.locator(grid + ' .ag-grid-scrolling-container .ag-row[row-index="0"]');
  async function horizontal(grid, x) {
    await page.locator(grid + ' .ag-body-horizontal-scroll-viewport').evaluate((el, left) => { el.scrollLeft=left; el.dispatchEvent(new Event('scroll')); }, x);
  }
  await page.goto(origin + '/fitet-ricevute/');
  await page.getByLabel('Username', { exact: true }).fill('fr-tester');
  await page.getByLabel('Password', { exact: true }).fill('FR-test-only-2026!');
  await page.getByRole('button', { name: 'Accedi', exact: true }).click();
  await row('#prices-grid').locator('[col-id="quota"]').waitFor();
  ok(await page.locator('#prices-grid .ag-grid-scrolling-container .ag-row').count() === 2 && await page.locator('#entries-grid').count() === 0, 'AG Grid prices and entries occupy separate pages');
  await row('#prices-grid').locator('[col-id="committee_label"]').filter({ hasText: 'Lombardia' }).waitFor();
  ok(true, 'price grid displays the committee name');
  const priceCell = row('#prices-grid').locator('[col-id="quota"]');
  await priceCell.dblclick();
  await priceCell.locator('input').fill('17,25');
  await priceCell.locator('input').press('Enter');
  await page.getByRole('status').filter({ hasText: 'Prezzo salvato.' }).waitFor();
  await page.waitForFunction(() => document.querySelector('#prices-grid .ag-row[row-index="0"] [col-id="quota"]')?.textContent.includes('17,25'));
  ok(true, 'editing AG Grid price commits immediately through API');
  await horizontal('#prices-grid', 1000);
  await row('#prices-grid').locator('[col-id="check"]').filter({ hasText: 'Non coincide' }).waitFor();
  ok(true, 'receipt mismatch and manual origin are shown after editing');
  await horizontal('#prices-grid', 0);
  await page.getByRole('button', { name: 'Sincronizza ricevute', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '1 ricevute sincronizzate su 1.' }).waitFor();
  ok(await page.locator('.last-sync time').count() === 1, 'successful synchronization displays completion date beside button');
  await page.reload();
  await page.locator('.last-sync time').waitFor();
  ok(await page.locator('.last-sync time').getAttribute('datetime'), 'completion date survives page reload');
  races = await (await client.get(api + 'gare')).json();
  ok(races.items.some(r => Number(r.manual_cents) === 1725), 'synchronization preserves the edited tariff');
  await page.screenshot({ path: resolve(__dirname, 'screenshots/prices-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: 'Iscrizioni', exact: true }).click();
  await row('#entries-grid').waitFor();
  ok(await page.locator('#prices-grid').count() === 0 && await page.locator('#entries-grid .ag-grid-scrolling-container .ag-row').count() === 6, 'entry page loads six registrations in AG Grid');
  entries = await (await client.get(api + 'iscrizioni')).json();
  ok(entries.items.filter(e => Number(e.race_id) === Number(id)).every(e => Number(e.price_cents) === 1725), 'entry amounts use the updated price after navigation');
  await page.getByLabel('Cerca iscrizioni', { exact: true }).fill('no-matching-athlete');
  await row('#entries-grid').waitFor({ state: 'hidden' });
  ok(await page.locator('#entries-grid .ag-grid-scrolling-container .ag-row').count() === 0, 'AG Grid filters registrations');
  await page.getByLabel('Cerca iscrizioni', { exact: true }).fill('');
  await row('#entries-grid').waitFor();
  await page.locator('#entries-grid .ag-header-cell[col-id="athletes"] .ag-header-cell-label').click();
  const before = await row('#entries-grid').locator('[col-id="athletes"]').innerText();
  await page.locator('#entries-grid .ag-header-cell[col-id="athletes"] .ag-header-cell-label').click();
  const after = await row('#entries-grid').locator('[col-id="athletes"]').innerText();
  ok(before !== after, 'AG Grid sorts registrations');
  ok(await page.getByRole('button', { name: 'Emetti rimborso (0)', exact: true }).isDisabled(), 'reimbursement action is disabled without checkbox selection');
  await page.locator('#entries-grid .ag-row[row-index="0"] .ag-selection-checkbox input').check();
  await page.locator('#entries-grid .ag-row[row-index="1"] .ag-selection-checkbox input').check();
  await page.getByRole('button', { name: 'Emetti rimborso (2)', exact: true }).click();
  await page.getByRole('heading', { name: 'Recap per atleta', exact: true }).waitFor();
  await row('#refund-grid').waitFor();
  ok(await page.locator('#refund-grid .ag-grid-scrolling-container .ag-row').count() === 2 && await page.locator('#athlete-grid .ag-grid-scrolling-container .ag-row').count() >= 1, 'refund page shows cumulative and per-athlete recaps');
  await page.getByLabel('Società emittente', { exact: true }).fill('Società di test');
  await page.getByLabel('Data ricevuta', { exact: true }).fill('2026-10-24');
  const firstDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Genera PDF', exact: true }).click();
  const pdf = await firstDownload; const pdfPath = resolve(out, 'cumulativo.pdf'); await pdf.saveAs(pdfPath);
  ok(readFileSync(pdfPath).subarray(0,5).toString() === '%PDF-', 'browser generates an actual cumulative PDF');
  await page.getByLabel('Formato PDF', { exact: true }).selectOption('both');
  const secondDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Genera PDF', exact: true }).click();
  const archive = await secondDownload; const zipPath = resolve(out, 'entrambi.zip'); await archive.saveAs(zipPath);
  const files = unzipSync(readFileSync(zipPath));
  ok(Object.keys(files).some(n => n.startsWith('rimborso-cumulativo')) && Object.keys(files).length >= 2, 'both output includes cumulative and individual PDFs in ZIP');
  for (const [name, bytes] of Object.entries(files)) { ok(Buffer.from(bytes).subarray(0,5).toString() === '%PDF-', 'valid PDF in archive: ' + name); writeFileSync(resolve(out, name), bytes); }
  await page.getByLabel('Formato PDF', { exact: true }).selectOption('athletes');
  const individualDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Genera PDF', exact: true }).click();
  const individual = await individualDownload; await individual.saveAs(resolve(out, 'solo-atleti.zip'));
  ok(!Object.keys(unzipSync(readFileSync(resolve(out,'solo-atleti.zip')))).some(n=>n.startsWith('rimborso-cumulativo')), 'individual output excludes cumulative PDF');
  await horizontal('#refund-grid', 1200);
  await row('#refund-grid').getByRole('button', { name: 'Segna rimborsata', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Quote segnate come rimborsate.' }).waitFor();
  await row('#refund-grid').getByRole('button', { name: 'Segna da rimborsare', exact: true }).waitFor();
  ok(true, 'refund status can be changed from recap');
  await page.screenshot({ path: resolve(__dirname, 'screenshots/refunds-desktop.png'), fullPage: true });
  await page.reload();
  await page.getByRole('heading', { name: 'Recap per atleta', exact: true }).waitFor();
  ok(await page.locator('#refund-grid .ag-grid-scrolling-container .ag-row').count() === 2, 'selection survives refund-page refresh');
  await page.getByRole('link', { name: 'Iscrizioni', exact: true }).click();
  await row('#entries-grid').waitFor();
  await horizontal('#entries-grid', 1200);
  await page.locator('#entries-grid .ag-grid-scrolling-container .ag-row').filter({ has: page.getByRole('button',{name:'Segna da rimborsare',exact:true}) }).first().getByRole('button',{name:'Segna da rimborsare',exact:true}).click();
  await page.getByRole('status').filter({ hasText: 'Quote riaperte come da rimborsare.' }).waitFor();
  ok(true, 'refund status can also be changed from entries page');
  await page.setViewportSize({ width: 390, height: 844 });
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile AG Grid scrolls internally without page overflow');
  await page.screenshot({ path: resolve(__dirname, 'screenshots/entries-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: 'Prezzi tornei', exact: true }).click();
  await row('#prices-grid').waitFor();
  await page.getByLabel('Cerca prezzi', { exact: true }).fill('no-matching-race');
  await row('#prices-grid').waitFor({ state: 'hidden' });
  ok(true, 'AG Grid filters price rows');
  await page.getByLabel('Cerca prezzi', { exact: true }).fill('');
  await page.setViewportSize({ width:1600,height:1100 });
  await horizontal('#prices-grid', 1600);
  await row('#prices-grid').getByRole('button', { name:'Ripristina automatico',exact:true }).click();
  await page.getByRole('status').filter({hasText:'Ripristinato il prezzo automatico.'}).waitFor();
  ok(true, 'explicit automatic price reset works in AG Grid');
  ok(errors.length === 0, 'new pages have no uncaught JavaScript errors: ' + errors.join('; '));
  for (const race of races.items) await client.patch(api+'prezzi/'+race.id, { headers, data:{manual_cents:null} });
  await client.patch(api+'rimborsi/stato',{headers,data:{ids,reimbursed:false}});
  const emptyTournament = { ...races.items[0], id: 999999, has_receipt: false, race_kind: 'empty', race_name: 'Nessuna iscrizione', entry_count: 0, receipt_entries: 0, price_cents: null, manual_cents: null, automatic_cents: null, receipt_total_cents: 0, calculated_total_cents: null, reconciliation: 'not_available', difference_cents: null };
  await page.route('**/wp-json/fitet-ricevute/v1/gare*', route => route.fulfill({json:{items:[emptyTournament],total:1,page:1,per_page:50}}));
  await page.reload();
  await row('#prices-grid').waitFor();
  await horizontal('#prices-grid',0);
  await row('#prices-grid').locator('[col-id="race_name"]').filter({hasText:'Nessuna iscrizione'}).waitFor();
  ok(true,'zero-entry tournament is visible in prices grid');
  const emptyQuota=row('#prices-grid').locator('[col-id="quota"]');
  await emptyQuota.dblclick();
  ok(await emptyQuota.locator('input').count()===0,'zero-entry placeholder does not allow editing fictitious quota');
  await horizontal('#prices-grid',1800);
  ok((await row('#prices-grid').locator('[col-id="check"]').innerText()).includes('Nessuna ricevuta'),'catalog-only tournament explicitly shows no PDF receipt');
  ok(await row('#prices-grid').getByRole('button',{name:'Ripristina automatico',exact:true}).isDisabled(),'zero-entry placeholder reset is disabled');
  await page.setViewportSize({width:390,height:844});
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'empty tournament view fits mobile width');
  await context.close(); await browser.close(); await client.dispose();
  console.log(checks + ' data/refund UI/API checks passed.');
};
